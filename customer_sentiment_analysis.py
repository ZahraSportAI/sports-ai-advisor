# ============================================
# ۲. تابع تحلیل احساسات
# ============================================

def analyze_sentiment(review: str) -> Dict:
    """تحلیل احساسات یک نظر با کلمات کلیدی"""

    positive_words = [
        "عالی", "خوب", "راضی", "خوشحال", "ممنون", "بین‌نظیر",
        "دقیقاً", "لطیفه", "راحته", "عالی"
    ]

    negative_words = [
        "بد", "ناراضی", "پشیمان", "دیر", "نبود", "گران",
        "معمولی", "کیفیت پایین", "شکایت", "ناامید", "تأخیر",
        "خراب", "معیوب", "مشکل", "پشیمانم", "کنده شد",
        "فرق داشت", "تیره‌تر", "اشتباه", "طول کشید", "خوب نیست"
    ]

    review_lower = review.lower()

    pos_count = sum(1 for w in positive_words if w in review_lower)
    neg_count = sum(1 for w in negative_words if w in review_lower)

    # امتیازدهی ویژه
    if "فوق‌العاده" in review_lower:
        pos_count += 2
    if "بین‌نظیر" in review_lower:
        pos_count += 2
    if "پشیمانم" in review_lower:
        neg_count += 3

    if pos_count > neg_count and pos_count > 0:
        sentiment = "مثبت"
        emoji = "✅"
    elif neg_count > pos_count and neg_count > 0:
        sentiment = "منفی"
        emoji = "❌"
    else:
        sentiment = "خنثی"
        emoji = "➖"

    return {
        "review": review,
        "sentiment": sentiment,
        "emoji": emoji,
        "positive_score": pos_count,
        "negative_score": neg_count
    }


